package com.breckneck.core.data.local

import androidx.room.ConstructedBy
import androidx.room.Database
import androidx.room.RoomDatabase
import androidx.room.RoomDatabaseConstructor
import com.breckneck.core.data.local.dao.DeckDao
import com.breckneck.core.data.local.dao.FlashcardDao
import com.breckneck.core.data.local.entity.DeckEntity
import com.breckneck.core.data.local.entity.FlashcardEntity

@Database(
    entities = [DeckEntity::class, FlashcardEntity::class],
    version = 1,
    exportSchema = true,
)
@ConstructedBy(RepetrailDatabaseConstructor::class)
abstract class RepetrailDatabase : RoomDatabase() {
    abstract fun deckDao(): DeckDao
    abstract fun flashcardDao(): FlashcardDao
}

// Actual implementations are generated by Room's KSP processor for each target.
@Suppress("KotlinNoActualForExpect")
expect object RepetrailDatabaseConstructor : RoomDatabaseConstructor<RepetrailDatabase> {
    override fun initialize(): RepetrailDatabase
}
